/* ------------------------------------------------------------------ accounts and statements */

export const bankAccounts = pgTable(
  "bank_accounts",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    bankName: text("bank_name").notNull(),
    /** As printed on the statement — often masked. Identity is scoped to the workspace. */
    accountIdentifier: text("account_identifier").notNull(),
    accountType: text("account_type"),
    /** A credit card is an account here too. `docs/decisions/0008` says why. */
    accountKind: accountKindEnum("account_kind").notNull().default("BANK_ACCOUNT"),
    /**
     * ISO 4217, validated against `src/money/currencies.ts` before it is written.
     *
     * Deliberately `text` rather than an enum: adding a currency should be a code change
     * with a test, not a migration. Set once, when the account is created, and never
     * rewritten — canonical transactions carry their own currency, so changing this later
     * would re-denominate movements already recorded against the account (Step 3a).
     */
    currency: text("currency").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // The lookup in upload-statement Step 3a never crosses a workspace, so neither does
    // this uniqueness.
    //
    // `accountKind` is deliberately NOT part of this. Two accounts are the same account
    // because they share a workspace, a bank and an identifier; including the kind would let
    // one account exist twice under two kinds, and since canonical transactions are keyed on
    // `bankAccountId`, a split account silently defeats deduplication — the one failure
    // Step 5a names as destroying a real payment.
    //
    // Matched case-insensitively, which is not fussiness. A model reading the same Axis
    // statement twice returned "AXIS BANK" once and "Axis Bank" the next time, and a
    // case-sensitive index made those two accounts for one real account — the same split,
    // arrived at by a different route. Case is how a statement is typeset, never which
    // account it is. `src/statements/account-identity.ts` holds the matching rule; it must
    // agree with this index exactly, and `tests/db/invariants.test.ts` pins that.
    uniqueIndex("bank_accounts_identity_idx").on(
      t.workspaceId,
      sql`lower(${t.bankName})`,
      sql`upper(${t.accountIdentifier})`,
    ),
  ],
);

/**
 * One uploaded file.
 *
 * `periodStart`/`periodEnd` are nullable only because they are unknown until the file is
 * identified; a statement cannot reach COMPLETED without them (upload-statement Step 3),
 * since Statement Coverage is derived from these columns.
 */
export const bankStatements = pgTable(
  "bank_statements",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    /** Null until Step 3a binds the statement to an account. */
    bankAccountId: uuid("bank_account_id").references(() => bankAccounts.id, {
      onDelete: "restrict",
    }),
    /**
     * The files of one upload, so a batch can be shown together.
     *
     * upload-statement §11: a batch is a presentation grouping and nothing more — the
     * files within it are processed independently and may reach different outcomes, so
     * nothing keyed on this column may make one file's fate depend on another's.
     */
    uploadBatchId: uuid("upload_batch_id").notNull(),
    filename: text("filename").notNull(),
    mimeType: text("mime_type").notNull(),
    storageRef: text("storage_ref").notNull(),
    state: statementStateEnum("state").notNull().default("UPLOADING"),
    /*
     * What identification read off the document, as printed.
     *
     * Separate from the bound `bankAccountId` on purpose. A statement in NEEDS_ACCOUNT
     * has these and no binding, and that is what the account picker shows the user; a
     * bound statement keeps them so a wrong binding can be traced back to what the
     * document actually said rather than to what we decided it meant.
     */
    identifiedBankName: text("identified_bank_name"),
    identifiedAccountIdentifier: text("identified_account_identifier"),
    identifiedAccountType: text("identified_account_type"),
    identifiedAccountKind: accountKindEnum("identified_account_kind"),
    /**
     * The currency code the document gave, raw — including one we do not support.
     *
     * Kept unvalidated on purpose. A statement in NEEDS_ACCOUNT because its currency was
     * unrecognised is only debuggable if what the model actually said survives; validating
     * on the way in would discard the one piece of evidence worth having.
     */
    identifiedCurrency: text("identified_currency"),
    validationOutcome: validationOutcomeEnum("validation_outcome"),
    failureReason: text("failure_reason"),
    periodStart: date("period_start"),
    periodEnd: date("period_end"),
    /** Null exactly when the period is. `docs/decisions/0008`. */
    periodSource: periodSourceEnum("period_source"),
    openingBalance: bigint("opening_balance", { mode: "bigint" }),
    closingBalance: bigint("closing_balance", { mode: "bigint" }),
    totalCredits: bigint("total_credits", { mode: "bigint" }),
    totalDebits: bigint("total_debits", { mode: "bigint" }),
    lineCount: integer("line_count"),
    /** The column mapping a model inferred, kept for debugging a bad parse. ADR 0003. */
    columnMapping: jsonb("column_mapping"),
    /**
     * A digest of the bytes, so the same document is recognisable as the same document.
     *
     * Its job is to keep canonical identity stable. The mapping is a model's answer and the
     * model does not always give the same one: two uploads of one ICICI statement chose
     * different description columns, 16% of the rows came out with different descriptions,
     * and since `description_normalized` is part of
     * `canonical_transactions_identity_idx` the second upload created 212 transactions that
     * already existed. Re-uploading a file now reuses the mapping already derived for those
     * exact bytes, so the descriptions are identical and deduplication holds.
     *
     * Not unique: the same statement may legitimately be uploaded twice, and that is the
     * case this exists to make safe.
     */
    contentHash: text("content_hash"),
    uploadedAt: timestamp("uploaded_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("bank_statements_workspace_idx").on(t.workspaceId),
    index("bank_statements_batch_idx").on(t.workspaceId, t.uploadBatchId),
    index("bank_statements_coverage_idx").on(t.bankAccountId, t.periodStart, t.periodEnd),
    // The lookup that reuses a mapping: this workspace's earlier copy of these exact bytes.
    index("bank_statements_content_idx").on(t.workspaceId, t.contentHash),
  ],
);

/**
 * One row exactly as extracted from one statement. Immutable evidence.
 *
 * Overlapping statements produce two of these for one payment; both point at the same
 * canonical transaction.
 */
export const statementLines = pgTable(
  "statement_lines",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    statementId: uuid("statement_id")
      .notNull()
      .references(() => bankStatements.id, { onDelete: "cascade" }),
    rowIndex: integer("row_index").notNull(),
    valueDate: date("value_date").notNull(),
    description: text("description").notNull(),
    amountMinor: bigint("amount_minor", { mode: "bigint" }).notNull(),
    direction: directionEnum("direction").notNull(),
    balanceMinor: bigint("balance_minor", { mode: "bigint" }),
    /**
     * The bank's own reference for this row — a UTR, a cheque number — as printed.
     *
     * Deliberately NOT unique here, unlike its counterpart on `canonical_transactions`.
     * Two overlapping statements both printing one UTR produce two of these rows and one
     * canonical transaction, which is the whole point of this table being evidence rather
     * than identity.
     *
     * It has to live on the line as well as on the transaction. Promotion runs in a
     * background workflow that may run twice, and it recovers by re-reading these rows —
     * so a reference held only in memory would be lost on a retry, and Step 5a's rule that
     * a reference decides identity on its own would silently stop applying to exactly the
     * statements that had already failed once.
     */
    externalReference: text("external_reference"),
    canonicalTransactionId: uuid("canonical_transaction_id").references(
      () => canonicalTransactions.id,
      { onDelete: "set null" },
    ),
  },
  (t) => [
    uniqueIndex("statement_lines_row_idx").on(t.statementId, t.rowIndex),
    index("statement_lines_canonical_idx").on(t.canonicalTransactionId),
  ],
);

/**
 * The business's single record of one financial movement.
 *
 * Everything downstream references this, never a statement line.
 */
export const canonicalTransactions = pgTable(
  "canonical_transactions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    bankAccountId: uuid("bank_account_id")
      .notNull()
      .references(() => bankAccounts.id, { onDelete: "cascade" }),
    valueDate: date("value_date").notNull(),
    /** Always positive; `direction` carries the sign. */
    amountMinor: bigint("amount_minor", { mode: "bigint" }).notNull(),
    direction: directionEnum("direction").notNull(),
    currency: text("currency").notNull(),
    description: text("description").notNull(),
    /** Case, whitespace and punctuation normalized. Formatting only — never interpreted. */
    descriptionNormalized: text("description_normalized").notNull(),
    /**
     * Distinguishes two legitimately identical payments on one day from the same payment
     * seen in two overlapping statements. upload-statement Step 5a.
     */
    occurrenceIndex: integer("occurrence_index").notNull().default(0),
    /** A bank-supplied reference or UTR. When present it alone establishes identity. */
    externalReference: text("external_reference"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // The dedup rule, as a constraint. A second upload of the same statement collides
    // here rather than silently creating duplicate transactions.
    uniqueIndex("canonical_transactions_identity_idx").on(
      t.bankAccountId,
      t.valueDate,
      t.amountMinor,
      t.direction,
      t.descriptionNormalized,
      t.occurrenceIndex,
    ),
    // When the bank gives a reference, it wins outright.
    uniqueIndex("canonical_transactions_reference_idx")
      .on(t.bankAccountId, t.externalReference)
      .where(sql`external_reference is not null`),
    index("canonical_transactions_workspace_date_idx").on(t.workspaceId, t.valueDate),
  ],
);

