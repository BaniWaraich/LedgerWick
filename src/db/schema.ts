/**
 * The authenticated user, and the table the Auth.js Drizzle adapter owns
 * (docs/decisions/0006-authentication.md).
 *
 * `id` is opaque and generated by the adapter. It is deliberately NOT the Google `sub`
 * claim — that lives one table over, in `accounts.providerAccountId`. What `0004` asked
 * for is that this schema stand alone rather than reference a provider-owned table, and
 * it does: these are our tables, in our migrations, so tests still run against a bare
 * Postgres with no auth schema present.
 *
 * `text` rather than `uuid` because the column holds whatever the auth provider's adapter
 * generates, which is not guaranteed to be a UUID.
 */
export const users = pgTable("users", {
  id: text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID()),
  email: text("email").notNull().unique(),
  // Null until the provider asserts it. Google always does; the column is nullable
  // because the adapter's user shape requires it to be.
  emailVerified: timestamp("email_verified", { withTimezone: true }),
  name: text("name"),
  image: text("image"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

